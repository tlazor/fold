"""Ground-truth linguistic measures that FOLD output is correlated against.

Each pairwise measure is a square DataFrame keyed by pipeline language code
(see languages.py), with a NaN diagonal since a language compared with itself
is not data. It is wrapped with what it measures, because the sign of a
correlation only means something once you know whether the measure is a
distance or a similarity. Measures load lazily and are cached.
"""

from dataclasses import dataclass
from functools import cache

import numpy as np
import pandas as pd

import constants
import languages
from paths import DATA_DIR
from wals_similarity import get_wals_similarity

_CONSTANTS_DIR = DATA_DIR / "constants"


@dataclass(frozen=True)
class Baseline:
    name: str  # label used in analysis output
    matrix: pd.DataFrame
    kind: str  # "distance" or "similarity"
    symmetric: bool
    scale: str  # units, and for asymmetric measures what rows/columns mean


def _square(df: pd.DataFrame, symmetric: bool) -> pd.DataFrame:
    """Numeric square matrix over the registry codes present as row and column.

    Other labels (summary rows such as "Mean", languages the pipeline can't
    analyse) are dropped.
    """
    codes = sorted(set(df.index) & set(df.columns) & set(languages.REGISTRY.index))
    df = df.loc[codes, codes].apply(pd.to_numeric, errors="coerce")
    if symmetric:
        df = df.combine_first(df.T)
    values = df.to_numpy(dtype=float, copy=True)
    np.fill_diagonal(values, np.nan)
    return pd.DataFrame(values, index=codes, columns=codes)


@cache
def mutual_intelligibility() -> Baseline:
    # Gooskens et al. (2018), one table per language family:
    # https://www.tandfonline.com/doi/full/10.1080/14790718.2017.1350185
    tables = [
        pd.read_csv(_CONSTANTS_DIR / f"{family}_intelligibility.csv", index_col=0)
        for family in ("germanic", "romance", "slavic")
    ]
    combined = tables[0].combine_first(tables[1]).combine_first(tables[2])
    return Baseline(
        name="mut_int",
        matrix=_square(combined, symmetric=False),
        kind="similarity",
        symmetric=False,
        scale="percent of the heard language understood (0-100); "
        "rows = listener's language, columns = language heard",
    )


@cache
def lexical_distance() -> Baseline:
    lex = pd.read_excel(DATA_DIR / "lexical-distance-matrix.xlsx", skiprows=2)
    # Drop the "branch" and "language" columns
    lex = lex.drop(columns=["Unnamed: 0", "Unnamed: 1"])

    # The spreadsheet's abbreviations aren't all ISO codes (Greek is "grk"),
    # so map them through the registry; languages outside it are dropped.
    code_by_abbr = languages.from_source_ids("lexdist_abbr")
    lex = lex[lex["Abreviation"].isin(code_by_abbr)]
    lex = lex.set_index(lex["Abreviation"].map(code_by_abbr))
    lex = lex[list(code_by_abbr)].rename(columns=code_by_abbr)
    return Baseline(
        name="lex_dist",
        matrix=_square(lex, symmetric=True),
        kind="distance",
        symmetric=True,
        scale="lexical distance (0-100)",
    )


@cache
def phonetic_distance() -> Baseline:
    # Generated by compute_lex_dist.py from ASJP word lists.
    ldnd = pd.read_csv(DATA_DIR / "asjp_ldnd_distances_by_iso2.csv", index_col=0)
    return Baseline(
        name="pho_dist",
        matrix=_square(ldnd, symmetric=True),
        kind="distance",
        symmetric=True,
        scale="ASJP LDND (about 0-1.05; about 1 = unrelated)",
    )


@cache
def wals_similarity() -> Baseline:
    sim = get_wals_similarity(languages.source_ids("wals_id"))
    return Baseline(
        name="wals_sim",
        matrix=_square(sim, symmetric=True),
        kind="similarity",
        symmetric=True,
        scale="IC-weighted share of WALS feature values in common (0-1)",
    )


def pairwise() -> list[Baseline]:
    return [
        mutual_intelligibility(),
        lexical_distance(),
        phonetic_distance(),
        wals_similarity(),
    ]


def fsi() -> pd.Series:
    """Weeks of study an English speaker needs (FSI): a distance from English."""
    return pd.Series(constants.FSI_SCALE, name="fsi")
